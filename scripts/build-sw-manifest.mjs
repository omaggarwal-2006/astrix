#!/usr/bin/env node
/**
 * Generates src/sw-manifest.js: the list of files the service worker caches for offline use.
 * Run after adding, moving or deleting any runtime file:   npm run build:sw
 * Check mode (used by CI) fails if the committed manifest is out of date:   node scripts/build-sw-manifest.mjs --check
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'src', 'sw-manifest.js');

// Everything the browser may request at runtime
const INCLUDE_DIRS = ['src', 'assets', 'engine'];
const INCLUDE_EXT = new Set(['.js', '.css', '.woff2', '.json', '.svg', '.png']);
const EXCLUDE = [/^engine\/ml\//, /^src\/sw-manifest\.js$/];

function walk(dir) {
  const abs = path.join(ROOT, dir);
  if (!fs.existsSync(abs)) return [];
  return fs.readdirSync(abs, { withFileTypes: true }).flatMap(d => {
    const rel = path.posix.join(dir, d.name);
    return d.isDirectory() ? walk(rel) : [rel];
  });
}

const files = INCLUDE_DIRS.flatMap(walk)
  .filter(f => INCLUDE_EXT.has(path.extname(f)) && !EXCLUDE.some(re => re.test(f)))
  .sort();
const assets = ['./', './index.html', ...files.map(f => './' + f)];

const text = `// GENERATED by scripts/build-sw-manifest.mjs. Do not edit by hand.
// Files cached by sw.js for offline use. Regenerate with: npm run build:sw
self.LANDFALL_ASSETS = ${JSON.stringify(assets, null, 2)};
`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== text) {
    console.error('src/sw-manifest.js is out of date. Run: npm run build:sw');
    process.exit(1);
  }
  console.log(`sw-manifest up to date (${assets.length} files)`);
} else {
  fs.writeFileSync(OUT, text);
  console.log(`wrote src/sw-manifest.js (${assets.length} files)`);
}
